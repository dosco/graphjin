// Command generate writes src/generated.ts, the TypeScript types OpenNeko
// uses to talk to GraphJin, from GraphJin's own Go types and config schema.
// Run it with `pnpm --filter @neko/graphjin-contract generate`.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"

	gjagent "github.com/dosco/graphjin/agent/v3"
	"github.com/dosco/graphjin/serv/v3"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: generate CONFIG_SCHEMA_JSON OUTPUT_TS")
		os.Exit(2)
	}
	out, err := generate(os.Args[1])
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.MkdirAll(filepath.Dir(os.Args[2]), 0o755); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(os.Args[2], out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(schemaPath string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by packages/graphjin-contract/generate from GraphJin's Go\n")
	b.WriteString("// types and serv/config.schema.json. DO NOT EDIT.\n\n")

	b.WriteString("// ─── Agent: POST /api/v1/agent, GET /api/v1/agent/status ───\n\n")
	structs := newStructWriter()
	for _, named := range []struct {
		name string
		v    any
	}{
		{"AgentRequest", gjagent.Request{}},
		{"AgentTurn", gjagent.Turn{}},
		{"AgentResponse", gjagent.Response{}},
		{"AgentRefusal", gjagent.Refusal{}},
		{"AgentUnblockStep", gjagent.UnblockStep{}},
		{"AgentResponseNotice", gjagent.ResponseNotice{}},
		{"AgentErrorInfo", gjagent.ErrorInfo{}},
		{"AgentSkillUsage", gjagent.SkillUsage{}},
		{"AgentPreparationStats", gjagent.PreparationStats{}},
		{"AgentUsageTotals", gjagent.UsageTotals{}},
		{"AgentActionEvent", gjagent.ActionEvent{}},
		{"AgentStatus", serv.AgentStatusResponse{}},
		{"AgentRateLimitConfig", gjagent.RateLimitConfig{}},
		{"AgentSelectionConfig", gjagent.SelectionConfig{}},
	} {
		structs.name(reflect.TypeOf(named.v), named.name)
	}
	if err := structs.writeAll(&b); err != nil {
		return nil, err
	}

	b.WriteString("// ─── Error codes in a GraphQL error's extensions.code ───\n\n")
	b.WriteString("export const GRAPHJIN_ERROR_CODES = {\n")
	fmt.Fprintf(&b, "  keystoreKeyRequired: %q,\n", serv.ErrorCodeKeystoreKeyRequired)
	b.WriteString("} as const;\n\n")
	b.WriteString("export type GraphjinErrorCode = (typeof GRAPHJIN_ERROR_CODES)[keyof typeof GRAPHJIN_ERROR_CODES];\n\n")
	b.WriteString("/** Begins the message of a keystore_key_required error, including in errors_json. */\n")
	fmt.Fprintf(&b, "export const GRAPHJIN_KEYSTORE_KEY_REQUIRED_MESSAGE = %q;\n\n", serv.KeystoreKeyRequiredMessage)

	b.WriteString("// ─── MCP tools ───\n\n")
	tools := append([]string(nil), serv.MCPAllToolNames()...)
	sort.Strings(tools)
	b.WriteString("/** Every MCP tool a GraphJin server may expose. */\n")
	b.WriteString("export const GRAPHJIN_MCP_TOOL_NAMES = [\n")
	for _, name := range tools {
		fmt.Fprintf(&b, "  %q,\n", name)
	}
	b.WriteString("] as const;\n\n")
	b.WriteString("export type GraphjinMcpToolName = (typeof GRAPHJIN_MCP_TOOL_NAMES)[number];\n\n")

	b.WriteString("// ─── Config: serv/config.schema.json ───\n\n")
	if err := writeSchema(&b, schemaPath); err != nil {
		return nil, err
	}
	return b.Bytes(), nil
}

// structWriter emits TypeScript types for Go structs and the structs they
// reference, each once.
type structWriter struct {
	names map[reflect.Type]string
	order []reflect.Type
}

func newStructWriter() *structWriter {
	return &structWriter{names: map[reflect.Type]string{}}
}

func (w *structWriter) name(t reflect.Type, name string) {
	if _, ok := w.names[t]; ok {
		return
	}
	w.names[t] = name
	w.order = append(w.order, t)
}

func (w *structWriter) writeAll(b *bytes.Buffer) error {
	for i := 0; i < len(w.order); i++ {
		t := w.order[i]
		fmt.Fprintf(b, "export type %s = {\n", w.names[t])
		if err := w.fields(b, t); err != nil {
			return err
		}
		b.WriteString("};\n\n")
	}
	return nil
}

func (w *structWriter) fields(b *bytes.Buffer, t reflect.Type) error {
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		if !f.IsExported() {
			continue
		}
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if f.Anonymous && name == "" {
			ft := f.Type
			if ft.Kind() == reflect.Pointer {
				ft = ft.Elem()
			}
			if err := w.fields(b, ft); err != nil {
				return err
			}
			continue
		}
		if name == "" {
			name = f.Name
		}
		optional := strings.Contains(opts, "omitempty") || f.Type.Kind() == reflect.Pointer
		ts, err := w.tsType(f.Type, t.Name()+"."+f.Name)
		if err != nil {
			return err
		}
		q := ""
		if optional {
			q = "?"
		}
		fmt.Fprintf(b, "  %s%s: %s;\n", name, q, ts)
	}
	return nil
}

func (w *structWriter) tsType(t reflect.Type, where string) (string, error) {
	switch t.Kind() {
	case reflect.Pointer:
		return w.tsType(t.Elem(), where)
	case reflect.String:
		return "string", nil
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.Interface:
		return "unknown", nil
	case reflect.Slice, reflect.Array:
		elem, err := w.tsType(t.Elem(), where)
		if err != nil {
			return "", err
		}
		if strings.ContainsAny(elem, " |") {
			elem = "(" + elem + ")"
		}
		return elem + "[]", nil
	case reflect.Map:
		elem, err := w.tsType(t.Elem(), where)
		if err != nil {
			return "", err
		}
		return "Record<string, " + elem + ">", nil
	case reflect.Struct:
		if t.PkgPath() == "time" && t.Name() == "Time" {
			return "string", nil
		}
		if _, ok := w.names[t]; !ok {
			w.name(t, "Agent"+t.Name())
		}
		return w.names[t], nil
	case reflect.Func:
		return "", fmt.Errorf("%s: a func field must be tagged json:\"-\"", where)
	}
	return "", fmt.Errorf("%s: unsupported Go kind %s", where, t.Kind())
}

// schema is the part of JSON Schema that config.schema.json uses.
type schema struct {
	Ref                  string             `json:"$ref"`
	Type                 json.RawMessage    `json:"type"`
	Title                string             `json:"title"`
	Description          string             `json:"description"`
	Properties           map[string]*schema `json:"properties"`
	AdditionalProperties json.RawMessage    `json:"additionalProperties"`
	Items                *schema            `json:"items"`
	Enum                 []any              `json:"enum"`
	Defs                 map[string]*schema `json:"$defs"`
}

func writeSchema(b *bytes.Buffer, path string) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	var root schema
	if err := json.Unmarshal(raw, &root); err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	defs := make([]string, 0, len(root.Defs))
	for name := range root.Defs {
		defs = append(defs, name)
	}
	sort.Strings(defs)
	for _, name := range defs {
		fmt.Fprintf(b, "export type GraphjinConfig%s = %s;\n\n", name, schemaType(root.Defs[name], ""))
	}
	b.WriteString("/** A GraphJin config file. */\n")
	fmt.Fprintf(b, "export type GraphjinConfig = %s;\n", schemaType(&root, ""))
	return nil
}

func schemaType(s *schema, indent string) string {
	if s == nil {
		return "unknown"
	}
	if s.Ref != "" {
		return "GraphjinConfig" + strings.TrimPrefix(s.Ref, "#/$defs/")
	}
	if len(s.Enum) > 0 {
		parts := make([]string, 0, len(s.Enum))
		for _, v := range s.Enum {
			j, _ := json.Marshal(v)
			parts = append(parts, string(j))
		}
		return strings.Join(parts, " | ")
	}
	types := schemaTypes(s.Type)
	if len(types) == 0 && len(s.Properties) > 0 {
		types = []string{"object"}
	}
	out := make([]string, 0, len(types))
	for _, t := range types {
		switch t {
		case "string":
			out = append(out, "string")
		case "integer", "number":
			out = append(out, "number")
		case "boolean":
			out = append(out, "boolean")
		case "null":
			out = append(out, "null")
		case "array":
			elem := schemaType(s.Items, indent)
			if strings.ContainsAny(elem, " |{") {
				elem = "(" + elem + ")"
			}
			out = append(out, elem+"[]")
		case "object":
			out = append(out, objectType(s, indent))
		}
	}
	if len(out) == 0 {
		return "unknown"
	}
	return strings.Join(out, " | ")
}

func objectType(s *schema, indent string) string {
	extra := ""
	if len(s.AdditionalProperties) > 0 && string(s.AdditionalProperties) != "false" {
		if string(s.AdditionalProperties) == "true" {
			extra = "unknown"
		} else {
			var ap schema
			if json.Unmarshal(s.AdditionalProperties, &ap) == nil {
				extra = schemaType(&ap, indent)
			}
		}
	}
	if len(s.Properties) == 0 {
		if extra == "" {
			extra = "unknown"
		}
		return "Record<string, " + extra + ">"
	}
	keys := make([]string, 0, len(s.Properties))
	for k := range s.Properties {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b strings.Builder
	b.WriteString("{\n")
	inner := indent + "  "
	for _, k := range keys {
		p := s.Properties[k]
		if doc := docComment(p); doc != "" {
			fmt.Fprintf(&b, "%s/** %s */\n", inner, doc)
		}
		fmt.Fprintf(&b, "%s%s?: %s;\n", inner, tsKey(k), schemaType(p, inner))
	}
	if extra != "" {
		fmt.Fprintf(&b, "%s[key: string]: %s;\n", inner, extra)
	}
	b.WriteString(indent + "}")
	return b.String()
}

func schemaTypes(raw json.RawMessage) []string {
	if len(raw) == 0 {
		return nil
	}
	var one string
	if json.Unmarshal(raw, &one) == nil {
		return []string{one}
	}
	var many []string
	_ = json.Unmarshal(raw, &many)
	return many
}

func docComment(s *schema) string {
	text := s.Title
	if s.Description != "" {
		if text != "" {
			text += ": "
		}
		text += s.Description
	}
	return strings.ReplaceAll(strings.ReplaceAll(text, "*/", "* /"), "\n", " ")
}

func tsKey(k string) string {
	for i, r := range k {
		if !(r == '_' || r == '$' || (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (i > 0 && r >= '0' && r <= '9')) {
			return fmt.Sprintf("%q", k)
		}
	}
	return k
}
