func TestDiscoveryUsesBatchMetadataForLargeCatalog(t *testing.T) {
	const tableCount = 5000

	dir := t.TempDir()
	captureDir := filepath.Join(dir, "capture")
	db := openRedshiftEmu(t, scaleSeed(tableCount), hostedemu.Config{
		CaptureDir: captureDir,
		TestName:   "redshift-discovery-scale",
		Backend:    hostedemu.BackendDuckDB,
		Fallback:   hostedemu.FallbackStrict,
	})
	defer db.Close()

	rows, err := db.QueryContext(context.Background(), `SHOW TABLES FROM SCHEMA dev.public`)
	if err != nil {
		t.Fatal(err)
	}
	var tables int
	for rows.Next() {
		tables++
	}
	if err := rows.Close(); err != nil {
		t.Fatal(err)
	}
	if tables != tableCount {
		t.Fatalf("SHOW TABLES rows = %d, want %d", tables, tableCount)
	}

	var cols int
	if err := db.QueryRowContext(context.Background(),
		`SELECT COUNT(*) FROM svv_all_columns WHERE table_name LIKE 'scale_table_%'`,
	).Scan(&cols); err != nil {
		t.Fatal(err)
	}
	if cols != tableCount*2 {
		t.Fatalf("SVV_ALL_COLUMNS scale columns = %d, want %d", cols, tableCount*2)
	}

	events, err := readCaptureEvents(hostedemu.CapturePath(captureDir, "redshift-discovery-scale"))
	if err != nil {
		t.Fatal(err)
	}
	var discoveryQueries int
	perTableShow := regexp.MustCompile(`(?i)^SHOW COLUMNS FROM TABLE .*scale_table_[0-9]{4}`)
	for _, ev := range events {
		if ev.Phase != "discovery" || ev.Op != "query" {
			continue
		}
		discoveryQueries++
		if perTableShow.MatchString(ev.NormalizedSQL) {
			t.Fatalf("per-table SHOW COLUMNS query detected: %s", ev.NormalizedSQL)
		}
	}
	if discoveryQueries > 2 {
		t.Fatalf("discovery query count = %d, want <= 2", discoveryQueries)
	}
}

func openRedshiftEmu(t *testing.T, seed string, conf hostedemu.Config) *sql.DB {
	t.Helper()
	dir := t.TempDir()
	seedPath := filepath.Join(dir, "redshift.sql")
	if err := os.WriteFile(seedPath, []byte(seed), 0644); err != nil {
		t.Fatal(err)
	}
	conf.SeedPath = seedPath
	if conf.TestName == "" {
		conf.TestName = "redshift-test"
	}
	db := sql.OpenDB(hostedemu.NewConnector(conf, NewAdapter()))
	if err := db.PingContext(context.Background()); err != nil {
		_ = db.Close()
		t.Fatal(err)
	}
	return db
}

func scaleSeed(n int) string {
	var b strings.Builder
	for i := 1; i <= n; i++ {
		fmt.Fprintf(&b, "CREATE TABLE scale_table_%04d (id BIGINT IDENTITY(1,1) PRIMARY KEY, name VARCHAR(120) ENCODE lzo) DISTSTYLE EVEN;\n", i)
	}
	return b.String()
}

type captureLine struct {
	Op            string `json:"op"`
	Phase         string `json:"phase"`
	NormalizedSQL string `json:"normalized_sql"`
}

func readCaptureEvents(path string) ([]captureLine, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()

	var out []captureLine
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		var ev captureLine
		if err := json.Unmarshal(sc.Bytes(), &ev); err != nil {
			return nil, err
		}
		out = append(out, ev)
	}
	return out, sc.Err()
}
