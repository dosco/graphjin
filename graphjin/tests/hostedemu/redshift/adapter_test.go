func TestTranslateSubscriptionUnbox(t *testing.T) {
	sql := `WITH _gj_sub AS (SELECT CAST(_gj_sub_unboxed.value[0] AS BIGINT) AS "id", CAST(_gj_sub_unboxed.value[1] AS VARCHAR) AS "cursor", _gj_sub_unboxed.idx AS "__gj_sub_order" FROM (SELECT JSON_PARSE(?) AS _gj_params) AS _gj_sub_input, UNNEST(_gj_sub_input._gj_params) WITH OFFSET AS _gj_sub_unboxed(value, idx)) SELECT (SELECT CAST(OBJECT_CONSTRUCT_KEEP_NULL('users', (SELECT OBJECT_CONSTRUCT_KEEP_NULL('id', "__sr_0"."id") AS "json" FROM (SELECT "users_0"."id" AS "id" FROM (SELECT "users"."id" FROM "public"."users" AS "users" WHERE (("users"."id") = "_gj_sub"."id") LIMIT 1) AS "users_0") AS "__sr_0")) AS VARCHAR) AS "__root" FROM ((SELECT true)) AS "__root_x") AS "__root" FROM _gj_sub ORDER BY "__gj_sub_order"`

	got := lowerRedshift(sql)
	for _, want := range []string{
		`json_each(CAST(? AS JSON))`,
		`CAST(json_extract(value, '$[0]') AS BIGINT) AS "id"`,
		`json_extract_string(value, '$[1]') AS "cursor"`,
		`CAST(key AS BIGINT) AS "__gj_sub_order"`,
		`json_object`,
		`ORDER BY "__gj_sub_order"`,
	} {
		if !strings.Contains(got, want) {
			t.Fatalf("translated subscription SQL missing %q:\n%s", want, got)
		}
	}
	for _, disallowed := range []string{`JSON_PARSE`, `UNNEST`, `OBJECT_CONSTRUCT`, `"public".`} {
		if strings.Contains(got, disallowed) {
			t.Fatalf("translated subscription SQL should not contain %q:\n%s", disallowed, got)
		}
	}
}

func TestDirectDDLLowering(t *testing.T) {
	db := openRedshiftEmu(t, redshiftFixture, hostedemu.Config{
		Backend:  hostedemu.BackendDuckDB,
		Fallback: hostedemu.FallbackStrict,
	})
	defer db.Close()

	ddl := `
CREATE TABLE public.events (
  id BIGINT IDENTITY(1,1) PRIMARY KEY,
  payload SUPER,
  body VARCHAR ENCODE lzo,
  created_at TIMESTAMPTZ
) DISTSTYLE AUTO ENCODE AUTO COMPOUND SORTKEY(created_at, id);
`
	lowered := lowerRedshiftDirect(ddl)
	for _, bad := range []string{"IDENTITY", "DISTSTYLE", "ENCODE AUTO", "SORTKEY", "SUPER", "TIMESTAMPTZ"} {
		if strings.Contains(strings.ToUpper(lowered), bad) {
			t.Fatalf("lowered DDL still contains %q:\n%s", bad, lowered)
		}
	}

	if _, err := db.ExecContext(context.Background(), ddl); err != nil {
		t.Fatalf("exec Redshift DDL through simulator: %v", err)
	}

	var count int
	if err := db.QueryRowContext(context.Background(), `SELECT COUNT(*) FROM events`).Scan(&count); err != nil {
		t.Fatalf("query created table: %v", err)
	}
}

func TestDiscoverySurfaces(t *testing.T) {
	db := openRedshiftEmu(t, redshiftFixture, hostedemu.Config{
		Backend:  hostedemu.BackendDuckDB,
		Fallback: hostedemu.FallbackStrict,
	})
	defer db.Close()

	var tableName, distStyle string
	if err := db.QueryRowContext(context.Background(),
		`SHOW TABLES FROM SCHEMA dev.public LIKE 'users' LIMIT 1`,
	).Scan(new(string), new(string), &tableName, new(string), new(string), new(string), new(string), new(any), new(any), &distStyle, new(string)); err != nil {
		t.Fatal(err)
	}
	if tableName != "users" || distStyle != "KEY(org_id)" {
		t.Fatalf("SHOW TABLES row = %q/%q, want users/KEY(org_id)", tableName, distStyle)
	}

	rows, err := db.QueryContext(context.Background(), `SHOW COLUMNS FROM TABLE dev.public.users`)
	if err != nil {
		t.Fatal(err)
	}
	defer rows.Close()
	var sawEmail, sawOrgID bool
	for rows.Next() {
		var databaseName, schemaName, tableName, columnName, nullable, dataType, remarks, sortKeyType, encoding, collation string
		var ordinal int64
		var columnDefault sql.NullString
		var charMax, precision, scale sql.NullInt64
		var sortKey sql.NullInt64
		var distKey bool
		if err := rows.Scan(&databaseName, &schemaName, &tableName, &columnName, &ordinal, &columnDefault, &nullable, &dataType, &charMax, &precision, &scale, &remarks, &sortKeyType, &sortKey, &distKey, &encoding, &collation); err != nil {
			t.Fatal(err)
		}
		switch columnName {
		case "email":
			sawEmail = true
			if dataType != "character varying" || encoding != "lzo" || nullable != "NO" {
				t.Fatalf("email SHOW COLUMNS = type %q encoding %q nullable %q", dataType, encoding, nullable)
			}
		case "org_id":
			sawOrgID = true
			if !distKey {
				t.Fatal("org_id dist_key = false, want true")
			}
		}
	}
	if err := rows.Err(); err != nil {
		t.Fatal(err)
	}
	if !sawEmail || !sawOrgID {
		t.Fatalf("SHOW COLUMNS saw email=%t org_id=%t, want both", sawEmail, sawOrgID)
	}

	var dataType string
	var distKey bool
	if err := db.QueryRowContext(context.Background(),
		`SELECT data_type, dist_key FROM svv_all_columns WHERE table_name = 'users' AND column_name = 'org_id'`,
	).Scan(&dataType, &distKey); err != nil {
		t.Fatal(err)
	}
	if dataType != "integer" || !distKey {
		t.Fatalf("SVV_ALL_COLUMNS org_id = %q/%t, want integer/true", dataType, distKey)
	}

	var pgType, pgEncoding string
	var pgSortKey int64
	if err := db.QueryRowContext(context.Background(),
		`SELECT "type", encoding, sortkey FROM pg_table_def WHERE tablename = 'users' AND "column" = 'created_at'`,
	).Scan(&pgType, &pgEncoding, &pgSortKey); err != nil {
		t.Fatal(err)
	}
	if pgType != "timestamptz" || pgEncoding != "raw" || pgSortKey != 1 {
		t.Fatalf("PG_TABLE_DEF created_at = %q/%q/%d, want timestamptz/raw/1", pgType, pgEncoding, pgSortKey)
	}
}

