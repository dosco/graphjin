const redshiftFixture = `
CREATE TABLE public.organizations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY(1,1) PRIMARY KEY,
  name VARCHAR(120) SORTKEY ENCODE lzo NOT NULL,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
) DISTSTYLE ALL ENCODE AUTO;

CREATE TABLE public.users (
  id BIGINT IDENTITY(1,1) PRIMARY KEY,
  org_id INTEGER REFERENCES public.organizations(id),
  email VARCHAR(255) ENCODE lzo NOT NULL,
  profile SUPER,
  sketch HLLSKETCH,
  shape GEOMETRY,
  payload VARBYTE,
  disabled BOOLEAN DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
) DISTSTYLE KEY DISTKEY(org_id) COMPOUND SORTKEY(created_at, id) ENCODE AUTO;
`

func TestParseSeedRedshiftDDL(t *testing.T) {
	schema, err := ParseSeedBytes([]byte(redshiftFixture))
	if err != nil {
		t.Fatal(err)
	}
	if len(schema.Tables) != 2 {
		t.Fatalf("tables = %d, want 2", len(schema.Tables))
	}

	users := schema.Table("public.users")
	if users == nil {
		t.Fatal("users table not parsed")
	}
	if users.DistStyle != "KEY" || users.DistKey != "org_id" {
		t.Fatalf("dist style/key = %q/%q, want KEY/org_id", users.DistStyle, users.DistKey)
	}
	if got := users.SortKeys; strings.Join(got, ",") != "created_at,id" {
		t.Fatalf("sort keys = %v, want [created_at id]", got)
	}

	id := users.Column("id")
	if id == nil || !id.Identity || !id.PrimaryKey || !id.NotNull {
		t.Fatalf("id column = %+v, want identity primary key not null", id)
	}
	orgID := users.Column("org_id")
	if orgID == nil || !orgID.DistKey || orgID.FKeyTable != "public.organizations" || orgID.FKeyColumn != "id" {
		t.Fatalf("org_id column = %+v, want distkey FK to organizations(id)", orgID)
	}
	email := users.Column("email")
	if email == nil || email.Encoding != "LZO" || !email.NotNull {
		t.Fatalf("email column = %+v, want LZO not null", email)
	}
	profile := users.Column("profile")
	if profile == nil || profile.Type != "SUPER" {
		t.Fatalf("profile column = %+v, want SUPER", profile)
	}

	orgs := schema.Table("organizations")
	if orgs == nil {
		t.Fatal("organizations table not parsed")
	}
	if orgs.DistStyle != "ALL" {
		t.Fatalf("organizations dist style = %q, want ALL", orgs.DistStyle)
	}
	orgPK := orgs.Column("id")
	if orgPK == nil || !orgPK.GeneratedIdentity || !orgPK.PrimaryKey {
		t.Fatalf("organizations id = %+v, want generated identity primary key", orgPK)
	}
}

func TestParseSeedRejectsPostgresOnlyDDL(t *testing.T) {
	tests := []struct {
		name string
		seed string
	}{
		{"json type", `CREATE TABLE bad (payload JSON);`},
		{"array type", `CREATE TABLE bad (tags VARCHAR[]);`},
		{"serial type", `CREATE TABLE bad (id SERIAL);`},
		{"index", `CREATE TABLE bad (id INT); CREATE INDEX bad_idx ON bad(id);`},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if _, err := ParseSeedBytes([]byte(tt.seed)); err == nil {
				t.Fatal("expected unsupported Redshift DDL error")
			}
		})
	}
}

